# 一段连续的「地址字符」（允许少量空格，因为有人会写成「浙江省 杭州市 西湖区 文三路 90号」）
_RUN = re.compile(rf"[{_CJK}A-Za-z0-9#\-—（）()·]+(?:[ 　][{_CJK}A-Za-z0-9#\-—（）()·]+){{0,8}}")

_REGION = re.compile(
    rf"^\s*((?:[{_CJK}]{{2,8}}?(?:省|自治区|特别行政区))?\s*(?:[{_CJK}]{{2,8}}?(?:市|自治州|地区|盟))?\s*"
    rf"(?:[{_CJK}]{{1,8}}?(?:区|县|市|旗))?)"
)


def looks_like_address(text: str) -> bool:
    """整段文字里是不是含有一个带细节成分的地址。"""
    return any(pattern.search(text) for pattern in _STRONG)


def split_address(text: str) -> tuple[str, str]:
    """把一个地址拆成 (省市区, 详细地址)；识别不出省市区时前半段为空。"""
    compact = re.sub(r"\s+", "", text)
    if compact and _REGION_ONLY.match(compact):
        return text, ""                      # 整段正好是省名或市名（「武汉」「浙江杭州」）：只有行政区，没有要遮的
    match = _REGION.match(text)
    region = match.group(1) if match else ""
    detail = text[len(region):]
    # 省市区后面一个字都没有，说明整段只有行政区，没有需要遮的详细地址
    if not detail.strip():
        return text, ""
    return region, detail


_LABEL_PREFIX = re.compile(r"^(?:收货地址|收件地址|寄件地址|派送地址|取件地址|详细地址|联系地址|家庭住址|收货地|收件地|寄件地|住址|地址)")


def _span_start(run: str) -> int:
    """从一段文字里找地址的起点：有省名就从省名开始，丢掉前面的「收件地址」之类的字。

    没有省名时（「地址文三路90号」这种标签直接粘在值前面），把开头的标签词去掉：
    这样同一个地址不管前面带不带标签，令牌化的是同一段文字，得到同一个令牌。"""
    best = -1
    for name in PROVINCES:
        at = run.find(name)
        if at >= 0 and (best < 0 or at < best):
            best = at
    if best >= 0:
        return best
    label = _LABEL_PREFIX.match(run)
    if label and len(run) - label.end() >= 4:
        return label.end()
    return 0


def find_addresses(text: str) -> list[tuple[int, int]]:
    """在任意文字里找出地址片段的位置 (起, 止)，起止之间的内容应整体送去令牌化。"""
    spans: list[tuple[int, int]] = []
    for run in _RUN.finditer(text):
        piece = run.group(0)
        if len(piece) < 6 or not looks_like_address(piece):
            continue
        start = run.start() + _span_start(piece)
        end = run.end()
        # 一段文字太长说明不是一个地址（比如整段说明），只处理命中细节成分的那一小段
        if end - start > 80:
            hit = next((m for p in _STRONG if (m := p.search(piece))), None)
            if hit is None:
                continue
            start, end = run.start() + hit.start(), run.start() + hit.end()
        spans.append((start, end))
    return spans
